"""The part library's files: where they go, what made them, and writing them.

Each generated FreeCAD file records a build key: a fingerprint of everything that
made it (the generator's sources, the data files, the shape's row and FreeCAD's
version). A file whose key matches is up to date, so it's left as it is; anything
else is built again. Runs in FreeCAD.
"""

from __future__ import annotations  # FreeCAD has no Document class to name at run time

import hashlib
import re
import subprocess
import tomllib
import zipfile
from collections.abc import Sequence
from pathlib import Path

import FreeCAD as App
import Part

REPO = Path(__file__).resolve().parents[2]
NOMINAL = Path.cwd() / "build" / "freecad" / "nominal"  # the verified CAD
AUTHOR = "Parametric Workshop"  # the project's name, never a person's (brief)
BUILD_KEY = "StudForgeBuild"  # the entry in a file's Meta that holds its build key


def build_key(row: object, sources: Sequence[Path]) -> str:
    """The fingerprint of everything that makes a shape's file, as 16 hex digits.

    `row` is the shape's settings; `sources` are the files its geometry and
    checks come from.
    """
    digest = hashlib.sha256()
    digest.update(".".join(App.Version()[:3]).encode())
    digest.update(repr(row).encode())
    for path in sources:
        digest.update(path.read_bytes())
    return digest.hexdigest()[:16]


def stored_key(fcstd: Path) -> str | None:
    """The build key a file was made with, read straight from it; None if it has none.

    An FCStd is a zip; its Document.xml holds the document's Meta entries.
    """
    if not fcstd.exists():
        return None
    with zipfile.ZipFile(fcstd) as archive:
        document = archive.read("Document.xml").decode()
    found = re.search(rf'<Item key="{BUILD_KEY}" value="([0-9a-f]+)"', document)
    return found.group(1) if found else None


def up_to_date(fcstd: Path, key: str) -> bool:
    """Whether a shape's files exist and were made from exactly these inputs."""
    return stored_key(fcstd) == key and fcstd.with_suffix(".step").exists()


def write(
    doc: App.Document, body: App.Body, folder: Path, key: str, about: list[str]
) -> None:
    """Save a checked shape's FCStd and STEP into a folder, with its build key.

    `about` is the STEP header's description of it; its first line ends with the
    part number, which names the files.
    """
    part_num = about[0].split()[-1]
    folder.mkdir(parents=True, exist_ok=True)
    doc.Label = part_num
    doc.CreatedBy = doc.Company = AUTHOR
    doc.Comment = f"Generated by {generator_version()}"
    doc.Meta = {**doc.Meta, BUILD_KEY: key}
    save(doc, folder / f"{part_num}.FCStd")
    export_step(body.Shape, folder / f"{part_num}.step", part_num, about)


def remove(part_num: str, folder: Path) -> None:
    """Delete a shape's files, so one that failed its check isn't left from before."""
    for suffix in (".FCStd", ".step"):
        (folder / f"{part_num}{suffix}").unlink(missing_ok=True)


def save(doc: App.Document, path: Path) -> None:
    """Save the document, replacing any older file there without a backup.

    FreeCAD keeps the file it saves over as a .FCBak. A generated file is always
    rebuilt from scratch, so its backup would only take space.
    """
    path.unlink(missing_ok=True)
    doc.saveAs(str(path))
    add_gui_document(doc, path)


def add_gui_document(doc: App.Document, path: Path) -> None:
    """Add to a saved file what the GUI shows: the objects whose Visibility is on.

    FreeCAD without its window saves no GuiDocument.xml, and the GUI then opens
    every object hidden, whatever its Visibility says. This writes the part of
    GuiDocument.xml that says which objects are shown (show_result picks them),
    and the empty camera entry the GUI reads after it.
    """
    shown = [obj.Name for obj in doc.Objects if obj.Visibility]
    entries = "".join(
        f'        <ViewProvider name="{name}">\n'
        '            <Properties Count="1">\n'
        '                <Property name="Visibility" type="App::PropertyBool">\n'
        '                    <Bool value="true"/>\n'
        "                </Property>\n"
        "            </Properties>\n"
        "        </ViewProvider>\n"
        for name in shown
    )
    xml = (
        "<?xml version='1.0' encoding='utf-8'?>\n"
        '<Document SchemaVersion="1">\n'
        f'    <ViewProviderData Count="{len(shown)}">\n{entries}'
        "    </ViewProviderData>\n"
        '    <Camera settings=""/>\n'  # FreeCAD reads one; empty keeps its view
        "</Document>\n"
    )
    with zipfile.ZipFile(path, "a", zipfile.ZIP_DEFLATED) as archive:
        archive.writestr("GuiDocument.xml", xml)


def export_step(shape: Part.Shape, path: Path, product: str, about: list[str]) -> None:
    """Write a STEP file whose header names its author, maker and contents.

    FreeCAD's exportStep fills the header with "FreeCAD" and Open CASCADE's
    defaults, so the header lines are rewritten afterwards: the author and
    organization become AUTHOR, the originating system generator_version(), the
    description the lines in `about`, and the product's name `product`, such as a
    part number. STEP text is ASCII, with ' written as ''.
    """
    shape.exportStep(str(path))
    text = path.read_text(encoding="ascii")

    def quoted(value: str) -> str:
        return "'" + value.replace("'", "''") + "'"

    stamp = re.search(r"FILE_NAME\('[^']*','([^']*)'", text)
    time = stamp.group(1) if stamp else ""
    lines = ",".join(quoted(line) for line in about)
    header = {
        r"FILE_DESCRIPTION\(.*?\);": f"FILE_DESCRIPTION(({lines}),'2;1');",
        r"FILE_NAME\(.*?\);": (
            f"FILE_NAME({quoted(path.name)},{quoted(time)},({quoted(AUTHOR)}),"
            f"({quoted(AUTHOR)}),'Open CASCADE STEP processor',"
            f"{quoted(generator_version())},'');"
        ),
        r"PRODUCT\('[^']*',\s*'[^']*'": f"PRODUCT({quoted(product)},{quoted(product)}",
    }
    # Each replaces the first match only, across lines; the replacement is given as
    # a function so nothing in it is read as a regular-expression escape.
    for pattern, line in header.items():
        text = re.sub(
            pattern, lambda _, line=line: line, text, count=1, flags=re.DOTALL
        )
    path.write_text(text, encoding="ascii")


def generator_version() -> str:
    """What made a file, such as "StudForge generator 0.0.0+c018a19 (FreeCAD 1.1.4)".

    The project's version from pyproject.toml, then the commit it was run from,
    with ".dirty" when there were uncommitted changes, then FreeCAD's version.
    """
    with (REPO / "pyproject.toml").open("rb") as file:
        version = tomllib.load(file)["project"]["version"]
    commit = git("rev-parse", "--short", "HEAD")
    dirty = ".dirty" if git("status", "--porcelain") else ""
    freecad = ".".join(App.Version()[:3])
    return f"StudForge generator {version}+{commit}{dirty} (FreeCAD {freecad})"


def git(*args: str) -> str:
    """A git command's output in the repo, or "unknown" if git can't say."""
    try:
        result = subprocess.run(
            ["git", "-C", str(REPO), *args], capture_output=True, text=True, check=True
        )
    except (OSError, subprocess.CalledProcessError):
        return "unknown"
    return result.stdout.strip()
